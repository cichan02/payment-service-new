package com.besmart.qrpay.paymentservice.util;

import com.besmart.qrpay.paymentservice.error.ApplicationError;
import com.besmart.qrpay.paymentservice.error.BusinessException;
import org.springframework.http.HttpStatus;

import java.time.Clock;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;

public final class TimeZones {

    public static final String DEFAULT_ZONE_ID = "Europe/Minsk";

    private static final DateTimeFormatter SOU_PATTERN = DateTimeFormatter.ofPattern("dd.MM.yyyy HH:mm:ss");
    private static final DateTimeFormatter ISO_PATTERN = DateTimeFormatter.ISO_LOCAL_DATE_TIME;

    private TimeZones() {
    }

    public static ZoneId zone(String timeZoneId) {
        if (timeZoneId == null || timeZoneId.isBlank()) {
            return ZoneId.of(DEFAULT_ZONE_ID);
        }
        try {
            return ZoneId.of(timeZoneId);
        } catch (RuntimeException ex) {
            throw new BusinessException(ApplicationError.VALIDATION_ERROR, HttpStatus.BAD_REQUEST,
                    "Unknown timeZoneId: " + timeZoneId);
        }
    }

    public static LocalDateTime nowInZone(Clock clock, String timeZoneId) {
        return LocalDateTime.ofInstant(clock.instant(), zone(timeZoneId));
    }

    public static LocalDateTime toUtc(LocalDateTime localDateTime, String timeZoneId) {
        return LocalDateTime.ofInstant(localDateTime.atZone(zone(timeZoneId)).toInstant(), ZoneOffset.UTC);
    }

    public static LocalDateTime fromUtc(LocalDateTime utcDateTime, String timeZoneId) {
        return LocalDateTime.ofInstant(utcDateTime.toInstant(ZoneOffset.UTC), zone(timeZoneId));
    }

    public static String format(LocalDateTime dateTime) {
        return dateTime.format(SOU_PATTERN);
    }

    /**
     * SOU returns operation time either in the legacy pattern or ISO-8601. A missing or
     * unparsable value must not fail the operation; callers keep the time generated by
     * this service in that case.
     */
    public static LocalDateTime parseSouOperationTime(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }
        try {
            return LocalDateTime.parse(value, SOU_PATTERN);
        } catch (DateTimeParseException first) {
            try {
                return LocalDateTime.parse(value, ISO_PATTERN);
            } catch (DateTimeParseException second) {
                return null;
            }
        }
    }
}
