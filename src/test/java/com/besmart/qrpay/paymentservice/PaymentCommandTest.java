package com.besmart.qrpay.paymentservice;

import com.besmart.qrpay.paymentservice.SouStub.Outcome;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;

import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class PaymentCommandTest extends AbstractIntegrationTest {

    @Test
    void paymentIsStoredAndDuplicateDoesNotCallSouAgain() throws Exception {
        Map<String, Object> request = paymentRequest("T-PAY", "trx-1", 10.50);

        ResponseEntity<Map> first = post("/payment", request);

        assertThat(first.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(code(first)).isZero();
        Map<?, ?> payment = data(first.getBody(), "payment");
        assertThat(payment.get("trnId")).isEqualTo("trx-1");
        assertThat(payment.get("state")).isEqualTo("COMPLETED");
        assertThat(payment.get("success")).isEqualTo(true);
        assertThat(((Number) payment.get("souId")).longValue()).isEqualTo(555);
        assertThat(first.getBody().get("slip")).isEqualTo("slip line 1\nslip line 2");
        assertThat(SOU.count("payment")).isEqualTo(1);

        assertThat(stateOf("T-PAY", "trx-1")).isEqualTo("COMPLETED");
        assertThat(receiptCount("T-PAY", "trx-1")).isEqualTo(1);

        // The SOU payload must use the operation time generated by this service, not a
        // value supplied by the caller, and must carry the terminal operation.
        Map<String, Object> sent = mapper.convertValue(
                mapper.readTree(SOU.last("payment").body()).get("souTerminalData"), Map.class);
        assertThat(sent.get("terminalId")).isEqualTo("T-PAY");
        assertThat(sent.get("trxId")).isEqualTo("trx-1");
        assertThat(sent.get("terminalDate")).isNotNull();

        ResponseEntity<Map> second = post("/payment", request);

        assertThat(second.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(code(second)).isZero();
        Map<?, ?> duplicate = data(second.getBody(), "payment");
        assertThat(((Number) duplicate.get("id")).longValue())
                .isEqualTo(((Number) payment.get("id")).longValue());
        assertThat(SOU.count("payment")).isEqualTo(1);
    }

    @Test
    void sameTrxWithDifferentAmountIsAConflict() {
        post("/payment", paymentRequest("T-CONFLICT", "trx-2", 10.00));

        ResponseEntity<Map> response = post("/payment", paymentRequest("T-CONFLICT", "trx-2", 20.00));

        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.CONFLICT);
        assertThat(code(response)).isEqualTo(-4402);
        assertThat(SOU.count("payment")).isEqualTo(1);
    }

    @Test
    void declineIsStoredAndNotRetried() {
        SOU.payment(Outcome.decline(-1234, "Declined by issuer"));
        Map<String, Object> request = paymentRequest("T-DECLINE", "trx-3", 15.00);

        ResponseEntity<Map> first = post("/payment", request);

        assertThat(first.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(code(first)).isEqualTo(-1234);
        assertThat(stateOf("T-DECLINE", "trx-3")).isEqualTo("DECLINED");
        assertThat(successOf("T-DECLINE", "trx-3")).isFalse();

        ResponseEntity<Map> second = post("/payment", request);

        assertThat(second.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(code(second)).isEqualTo(-4404);
        assertThat(SOU.count("payment")).isEqualTo(1);
    }

    @Test
    void souOutageLeavesRowRetryable() {
        SOU.payment(Outcome.httpError());
        Map<String, Object> request = paymentRequest("T-RETRY", "trx-4", 30.00);

        ResponseEntity<Map> failed = post("/payment", request);

        assertThat(failed.getStatusCode()).isEqualTo(HttpStatus.SERVICE_UNAVAILABLE);
        assertThat(code(failed)).isEqualTo(-1300);
        assertThat(stateOf("T-RETRY", "trx-4")).isEqualTo("CREATED");
        assertThat(successOf("T-RETRY", "trx-4")).isFalse();

        SOU.payment(Outcome.success(901));
        ResponseEntity<Map> retried = post("/payment", request);

        assertThat(retried.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(code(retried)).isZero();
        assertThat(stateOf("T-RETRY", "trx-4")).isEqualTo("COMPLETED");
        assertThat(((Number) data(retried.getBody(), "payment").get("souId")).longValue())
                .isEqualTo(901);
        assertThat(SOU.count("payment")).isEqualTo(2);
    }

    @Test
    void invalidRequestIsRejectedBeforeAnySouCall() {
        Map<String, Object> request = paymentRequest("T-BAD", "trx-5", 5.00);
        request.remove("trxId");

        ResponseEntity<Map> response = post("/payment", request);

        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(code(response)).isEqualTo(-4401);
        assertThat(SOU.count("payment")).isZero();
        assertThat(jdbc.queryForObject(
                "select count(*) from public.payment where cash_desk_uid = 'T-BAD'",
                Integer.class)).isZero();
    }

    private int code(ResponseEntity<Map> response) {
        return ((Number) response.getBody().get("errorCode")).intValue();
    }

    private int receiptCount(String terminalId, String trnId) {
        return jdbc.queryForObject(
                "select count(*) from public.receipt r join public.payment p on p.id = r.payment_id "
                        + "where p.cash_desk_uid = ? and p.trn_id = ?",
                Integer.class, terminalId, trnId);
    }
}
